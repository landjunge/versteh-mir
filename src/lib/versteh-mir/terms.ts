export function pickOneTerm(text: string, already: string[]): string | null {
  const used = new Set(already.map((w) => w.toLowerCase()));
  const words = text.match(/[A-Za-zÄÖÜäöüß]{3,}/g) ?? [];
  for (const word of words) {
    const key = word.toLowerCase();
    if (STOP.has(key) || used.has(key)) continue;
    return word;
  }
  const fallback = words.find((w) => !used.has(w.toLowerCase()));
  return fallback ?? null;
}
